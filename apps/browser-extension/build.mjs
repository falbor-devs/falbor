// Falbor Automation extension build script.
//
// Uses only Node built-ins. Source modules are concatenated into classic
// scripts (MV3 forbids cross-file ES module imports in content scripts, and
// Firefox MV3 background.scripts does not support modules reliably), then the
// popup assets, icons and manifest are written per browser.

import { rmSync, mkdirSync, readFileSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateSync } from 'node:zlib';
import { spawnSync } from 'node:child_process';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, 'src');
const DIST = join(ROOT, 'dist');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const VERSION = pkg.version || '1.0.0';
const ICON_COLOR = [0xe0, 0x36, 0x02]; // Falbor orange #E03602
const ICON_SIZES = [16, 32, 48, 128];
const BROWSERS = ['chrome', 'firefox'];
const COPIED_FILES = ['popup.html', 'popup.css', 'popup.js', 'content.css'];

const HEADER = '/* Generated by build.mjs from src/. Do not edit dist/ directly. */\n';

// --- PNG encoder (about 50 lines, valid PNG with real CRCs) ---

let crcTableCache = null;

function crcTable() {
  if (crcTableCache) return crcTableCache;
  const table = new Int32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c;
  }
  crcTableCache = table;
  return table;
}

function crc32(buf) {
  const table = crcTable();
  let crc = 0xffffffff;
  for (let i = 0; i < buf.length; i += 1) {
    crc = table[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length, 0);
  const typeBuf = Buffer.from(type, 'ascii');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])), 0);
  return Buffer.concat([length, typeBuf, data, crc]);
}

function solidPng(size) {
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // color type: truecolor RGB
  ihdr[10] = 0; // compression: deflate
  ihdr[11] = 0; // filter method
  ihdr[12] = 0; // interlace
  const row = Buffer.alloc(1 + size * 3);
  row[0] = 0; // filter type 0 for each scanline
  for (let x = 0; x < size; x += 1) {
    row[1 + x * 3] = ICON_COLOR[0];
    row[2 + x * 3] = ICON_COLOR[1];
    row[3 + x * 3] = ICON_COLOR[2];
  }
  const raw = Buffer.concat(Array.from({ length: size }, () => row));
  return Buffer.concat([
    signature,
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', deflateSync(raw)),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}

// --- bundling ---

function stripExports(code) {
  return code.replace(/^export\s+(default\s+)?/gm, '');
}

function bundle(files, wrap) {
  const parts = files.map((file) => stripExports(readFileSync(join(SRC, file), 'utf8')));
  const body = parts.join('\n\n');
  if (!wrap) return HEADER + body + '\n';
  return HEADER + "(function () {\n'use strict';\n\n" + body + '\n})();\n';
}

function buildBrowser(browser) {
  const outDir = join(DIST, browser);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(join(outDir, 'icons'), { recursive: true });

  // background.js: lib + config + agent engine + background, one classic script.
  writeFileSync(
    join(outDir, 'background.js'),
    bundle(['lib/browser.js', 'lib/api.js', 'config.js', 'agent.js', 'background.js'], true),
  );

  // content.js: text helpers + Reddit DOM adapter + agent overlay + runner.
  writeFileSync(join(outDir, 'content.js'), bundle(['lib/text.js', 'lib/reddit.js', 'overlay.js', 'content.js'], true));

  // shared.js: lib + config for the popup (loaded before popup.js).
  writeFileSync(join(outDir, 'shared.js'), bundle(['lib/browser.js', 'lib/api.js', 'config.js'], false));

  for (const file of COPIED_FILES) {
    copyFileSync(join(SRC, file), join(outDir, file));
  }

  for (const size of ICON_SIZES) {
    writeFileSync(join(outDir, 'icons', 'icon' + size + '.png'), solidPng(size));
  }

  const manifest = JSON.parse(readFileSync(join(SRC, 'manifest.' + browser + '.json'), 'utf8'));
  manifest.version = VERSION;
  writeFileSync(join(outDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

  console.log('Built dist/' + browser + '/');
  console.log('  manifest.json (v' + VERSION + ')');
  console.log('  background.js, content.js, shared.js');
  console.log('  popup.html, popup.css, popup.js, content.css');
  console.log('  icons/icon{16,32,48,128}.png');
}

function packageBrowsers() {
  let failures = 0;
  for (const browser of BROWSERS) {
    const dir = join(DIST, browser);
    if (!existsSync(dir)) {
      console.error('dist/' + browser + '/ does not exist. Run "node build.mjs ' + browser + '" first.');
      failures += 1;
      continue;
    }
    const outFile = join(ROOT, 'falbor-automation-' + browser + '-v' + VERSION + '.zip');
    rmSync(outFile, { force: true });
    const result = spawnSync('zip', ['-r', '-q', outFile, '.'], { cwd: dir });
    if (result.error || result.status !== 0) {
      const reason = result.error ? result.error.message : 'zip exited with code ' + result.status;
      console.error('Could not create ' + outFile + ' (' + reason + ').');
      console.error('Zip manually instead: (cd dist/' + browser + ' && zip -r ../../falbor-automation-' + browser + '-v' + VERSION + '.zip .)');
      failures += 1;
      continue;
    }
    console.log('Packaged ' + outFile);
  }
  if (failures > 0) process.exitCode = 1;
}

function main() {
  const command = (process.argv[2] || 'all').toLowerCase();
  if (command === 'chrome' || command === 'firefox') {
    buildBrowser(command);
    return;
  }
  if (command === 'package') {
    packageBrowsers();
    return;
  }
  if (command === 'all') {
    for (const browser of BROWSERS) buildBrowser(browser);
    return;
  }
  console.error('Unknown command "' + command + '". Usage: node build.mjs [chrome|firefox|package|all]');
  process.exitCode = 1;
}

main();
